/**
 * A sign-in window the plugin owns.
 *
 * The provider's auth flow only redirects to its own callback, and the desktop
 * app receives the issued token by watching that redirect inside a window it
 * controls. A plain system browser cannot hand the URL back to us, and a
 * loopback redirect is ignored by the auth endpoint (verified: it always answers
 * 302 with a hard-coded `redirect_uri`). So we do what the app does — open our
 * own window and read the URLs it navigates through.
 *
 * No credentials are harvested here. The user types their phone number and SMS
 * code into the provider's own page; this code only reads the redirect URL the
 * provider itself produces, exactly as the official client does.
 *
 * The window is launched as a separate Electron process: the plugin runs inside
 * the harness's own Electron instance, which cannot create further windows for
 * a plugin, and a helper process keeps a failed sign-in from touching DSH.
 *
 * @module src/loginwindow.js
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawn } from 'node:child_process'

/** Where the window writes its progress; the host polls this file. */
export function channelDir(stateDir) {
  return path.join(stateDir ?? path.join(os.homedir(), '.dsh/teleagent'), 'login-window')
}

/**
 * Locate an Electron binary.
 *
 * Order matters: a binary the user configured wins, then the copy DSH already
 * downloaded for its own plugins, then any local install.
 */
export function findElectron() {
  const candidates = [
    process.env.TA_ELECTRON_PATH,
    path.join(os.homedir(), '.dsh/electron/Electron.app/Contents/MacOS/Electron'),
    path.join(os.homedir(), '.dsh/electron/electron'),
    // Linux/Windows shapes, for completeness.
    path.join(os.homedir(), '.dsh/electron/electron'),
    path.join(os.homedir(), '.dsh/electron/Electron.exe'),
  ].filter(Boolean)
  for (const c of candidates) {
    try { if (fs.statSync(c).isFile()) return c } catch {}
  }
  return null
}

/** The Electron main script is written next to the state so it can be inspected. */
function mainScriptSource(entryUrl) {
  return `// Generated by dsh-teleagent. Owns one sign-in window and reports every
// navigation back to the host through files in the channel directory.
const { app, BrowserWindow, session } = require('electron')
const fs = require('fs')
const path = require('path')

const DIR = ${JSON.stringify('__CHANNEL_DIR__')}
const ENTRY = ${JSON.stringify(entryUrl)}
const write = (name, value) => {
  try { fs.mkdirSync(DIR, { recursive: true }); fs.writeFileSync(path.join(DIR, name), String(value)) } catch {}
}
const log = (line) => {
  try { fs.appendFileSync(path.join(DIR, 'window.log'), new Date().toISOString() + ' ' + line + '\\n') } catch {}
}

app.whenReady().then(async () => {
  log('ready electron=' + process.versions.electron)
  const win = new BrowserWindow({ width: 960, height: 760, title: 'TeleAgent 登录' })
  let settled = false

  const inspect = (url) => {
    write('current-url', url)
    const m = /[?&#]token=([^&]+)/.exec(url)
    if (m && !settled) {
      settled = true
      write('token', decodeURIComponent(m[1]))
      write('status', 'done')
      log('token captured')
      setTimeout(() => app.exit(0), 400)
      return
    }
    if (/\\/cowork\\/auth/.test(url) && /code=/.test(url) && !settled) {
      // The callback arrived without a token in the URL: the code has to be
      // exchanged, which only the provider's page can do, so keep the window
      // open and let the page finish.
      log('auth callback without token; waiting for the page to complete')
    }
  }

  win.webContents.on('did-navigate', (_e, url) => { log('navigate ' + url); inspect(url) })
  win.webContents.on('did-navigate-in-page', (_e, url) => { log('navigate-in-page ' + url); inspect(url) })
  win.webContents.on('did-fail-load', (_e, code, desc, url) => log('fail ' + code + ' ' + desc + ' ' + url))
  win.on('closed', () => { write('status', settled ? 'done' : 'closed'); app.exit(0) })

  write('status', 'open')
  await win.loadURL(ENTRY)
  log('loaded')
})

// Never let a crash in the window take anything else down with it.
process.on('uncaughtException', (e) => { write('status', 'error'); write('error', String(e && e.message || e)); app.exit(1) })
`
}

/**
 * Open the sign-in window.
 *
 * Returns as soon as the process is started: the caller polls the channel
 * directory for the token, so a slow sign-in never blocks a request.
 */
export function openLoginWindow({ entryUrl, stateDir, electronPath } = {}) {
  const electron = electronPath || findElectron()
  if (!electron) return { ok: false, error: 'no Electron runtime found (set TA_ELECTRON_PATH)' }
  if (!entryUrl) return { ok: false, error: 'entryUrl is required' }

  const dir = channelDir(stateDir)
  fs.mkdirSync(dir, { recursive: true })
  for (const f of ['token', 'status', 'error', 'current-url', 'window.log']) {
    try { fs.unlinkSync(path.join(dir, f)) } catch {}
  }

  const script = path.join(dir, 'main.cjs')
  fs.writeFileSync(script, mainScriptSource(entryUrl).replace('__CHANNEL_DIR__', dir))

  // ELECTRON_RUN_AS_NODE would make the binary behave as plain Node and the
  // window would never appear, so it is explicitly removed for the child.
  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE

  const child = spawn(electron, [script], { env, stdio: 'ignore', detached: true })
  child.unref()
  return { ok: true, pid: child.pid, dir, electron }
}

/** Poll for the window's outcome. */
export function readLoginWindow(stateDir) {
  const dir = channelDir(stateDir)
  const read = (f) => { try { return fs.readFileSync(path.join(dir, f), 'utf8').trim() } catch { return null } }
  const status = read('status')
  const token = read('token')
  return {
    status,
    token,
    error: read('error'),
    currentUrl: read('current-url'),
    dir,
    done: Boolean(token),
    closed: status === 'closed' || status === 'error',
  }
}
