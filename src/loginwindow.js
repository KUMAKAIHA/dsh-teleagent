/**
 * A sign-in window the plugin owns.
 *
 * The provider's auth flow only redirects to its own callback, and the desktop
 * app receives the issued token by watching that redirect inside a window it
 * controls. A plain system browser cannot hand the URL back to us, and a
 * loopback redirect is ignored by the auth endpoint (verified: it always answers
 * 302 with a hard-coded `redirect_uri`). So we do what the app does — open our
 * own window and read the URLs it navigates through.
 *
 * No credentials are harvested here. The user types their phone number and SMS
 * code into the provider's own page; this code only reads the redirect URL the
 * provider itself produces, exactly as the official client does.
 *
 * The window is launched as a separate Electron process: the plugin runs inside
 * the harness's own Electron instance, which cannot create further windows for
 * a plugin, and a helper process keeps a failed sign-in from touching DSH.
 *
 * @module src/loginwindow.js
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { spawn } from 'node:child_process'

/** Where the window writes its progress; the host polls this file. */
export function channelDir(stateDir) {
  return path.join(stateDir ?? path.join(os.homedir(), '.dsh/teleagent'), 'login-window')
}

/**
 * Locate an Electron binary.
 *
 * Order matters: a binary the user configured wins, then the copy DSH already
 * downloaded for its own plugins, then any local install.
 */
export function findElectron() {
  const candidates = [
    process.env.TA_ELECTRON_PATH,
    path.join(os.homedir(), '.dsh/electron/Electron.app/Contents/MacOS/Electron'),
    path.join(os.homedir(), '.dsh/electron/electron'),
    // Linux/Windows shapes, for completeness.
    path.join(os.homedir(), '.dsh/electron/electron'),
    path.join(os.homedir(), '.dsh/electron/Electron.exe'),
  ].filter(Boolean)
  for (const c of candidates) {
    try { if (fs.statSync(c).isFile()) return c } catch {}
  }
  return null
}

/** The Electron main script is written next to the state so it can be inspected. */
function mainScriptSource(entryUrl) {
  return `// Generated by dsh-teleagent. Owns one sign-in window and reports every
// navigation back to the host through files in the channel directory.
const { app, BrowserWindow, session } = require('electron')
const fs = require('fs')
const path = require('path')

const DIR = ${JSON.stringify('__CHANNEL_DIR__')}
const ENTRY = ${JSON.stringify(entryUrl)}
const write = (name, value) => {
  try { fs.mkdirSync(DIR, { recursive: true }); fs.writeFileSync(path.join(DIR, name), String(value)) } catch {}
}
const log = (line) => {
  try { fs.appendFileSync(path.join(DIR, 'window.log'), new Date().toISOString() + ' ' + line + '\\n') } catch {}
}

app.whenReady().then(async () => {
  log('ready electron=' + process.versions.electron)

  // Cookies are where the session actually lives: the provider answers the auth
  // callback with Set-Cookie (X-Token / operationToken / operToken), and the
  // desktop client reads its session from that cookie jar — its sign-out even
  // clears cookies for the SSO origin rather than local storage. Without a
  // persistent session here, the exchange completes in the page and the token is
  // thrown away with the window.
  const PARTITION = 'persist:teleagent-login'
  const ses = session.fromPartition(PARTITION)

  const win = new BrowserWindow({
    width: 960, height: 760, title: 'TeleAgent 登录',
    webPreferences: { partition: PARTITION },
  })
  let settled = false

  /** Read the session credential out of the cookie jar. */
  const tokenFromCookies = async () => {
    try {
      const all = await ses.cookies.get({})
      const pick = (name) => {
        const c = all.filter((x) => x.name === name && x.value).pop()
        return c ? decodeURIComponent(c.value) : null
      }
      return pick('X-Token') || pick('operationToken') || pick('operToken') || null
    } catch (e) { log('cookie read failed: ' + e.message); return null }
  }

  const settle = async (reason) => {
    if (settled) return
    const tok = await tokenFromCookies()
    if (!tok) { log('no credential in cookies yet (' + reason + ')'); return }
    settled = true
    write('token', tok)
    write('status', 'done')
    log('credential captured from cookies (' + reason + ')')
    setTimeout(() => app.exit(0), 400)
  }

  const inspect = (url) => {
    write('current-url', url)
    let u
    try { u = new URL(url) } catch { return }

    // A token is preferred when present, but usually is NOT: the callback
    // carries only a code. The official client treats that code as the
    // credential (it reads the code and hands it straight to completeLogin), so
    // we accept it the same way. Waiting for a token here is what left every
    // sign-in looking like it never completed.
    const code = u.searchParams.get('code')
    const token = u.searchParams.get('token')
    const isCallback = u.pathname.includes('/cowork/auth')

    // A token in the URL is final. A bare code is NOT: it is a one-time grant
    // that the callback page still has to exchange, and the result arrives as a
    // cookie. So on code we keep the window open and let the page run.
    if (token && isCallback && !settled) {
      settled = true
      write('token', token)
      write('status', 'done')
      log('credential captured (url token)')
      setTimeout(() => app.exit(0), 400)
      return
    }
    if (code && isCallback) {
      write('code', code)
      log('auth code seen; waiting for the page to exchange it')
      setTimeout(() => settle('after callback'), 1500)
    }
  }

  win.webContents.on('did-navigate', (_e, url) => { log('navigate ' + url); inspect(url) })
  win.webContents.on('did-navigate-in-page', (_e, url) => { log('navigate-in-page ' + url); inspect(url) })
  win.webContents.on('did-fail-load', (_e, code, desc, url) => log('fail ' + code + ' ' + desc + ' ' + url))
  win.on('closed', () => { write('status', settled ? 'done' : 'closed'); app.exit(0) })

  // Refuse to hand the OS the app's deeplink.
  //
  // When the callback page finishes it navigates to 'teleai-cowork://...', which
  // makes macOS launch the TeleAgent app. We do not want that: the credential is
  // already available in our own cookie jar, and launching another app is a
  // surprising side effect of pressing sign-in here. The official client also
  // intercepts this instead of letting the OS handle it (it calls
  // preventDefault and dispatches internally).
  // Anything that is not http(s) would be handed to the OS (the app's own
  // protocol is 'teleai-cowork://'). http(s) navigation must still work.
  const isDeeplink = (url) => typeof url === 'string' && !/^https?:\/\//i.test(url)
  const blockDeeplink = (event, url) => {
    if (!isDeeplink(url)) return
    event.preventDefault()
    log('blocked deeplink navigation: ' + String(url).slice(0, 60))
    // The exchange has already happened by now; grab the credential immediately.
    setTimeout(() => settle('deeplink blocked'), 300)
  }
  win.webContents.on('will-navigate', blockDeeplink)
  win.webContents.on('will-redirect', blockDeeplink)
  win.webContents.on('will-frame-navigate', (e) => blockDeeplink(e, e.url))
  // Any attempt to open a new window goes through here; deny it outright.
  win.webContents.setWindowOpenHandler(({ url }) => {
    log('denied window.open: ' + String(url).slice(0, 60))
    return { action: 'deny' }
  })

  write('status', 'open')
  await win.loadURL(ENTRY)
  log('loaded')

  // The exchange can also finish without a further navigation, so poll as well.
  const timer = setInterval(() => { settle('poll') }, 2000)
  win.on('closed', () => clearInterval(timer))
})

// Never let a crash in the window take anything else down with it.
process.on('uncaughtException', (e) => { write('status', 'error'); write('error', String(e && e.message || e)); app.exit(1) })
`
}

/**
 * Open the sign-in window.
 *
 * Returns as soon as the process is started: the caller polls the channel
 * directory for the token, so a slow sign-in never blocks a request.
 */
export function openLoginWindow({ entryUrl, stateDir, electronPath } = {}) {
  const electron = electronPath || findElectron()
  if (!electron) return { ok: false, error: 'no Electron runtime found (set TA_ELECTRON_PATH)' }
  if (!entryUrl) return { ok: false, error: 'entryUrl is required' }

  const dir = channelDir(stateDir)
  fs.mkdirSync(dir, { recursive: true })
  for (const f of ['token', 'status', 'error', 'current-url', 'window.log']) {
    try { fs.unlinkSync(path.join(dir, f)) } catch {}
  }

  const script = path.join(dir, 'main.cjs')
  fs.writeFileSync(script, mainScriptSource(entryUrl).replace('__CHANNEL_DIR__', dir))

  // ELECTRON_RUN_AS_NODE would make the binary behave as plain Node and the
  // window would never appear, so it is explicitly removed for the child.
  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE

  const child = spawn(electron, [script], { env, stdio: 'ignore', detached: true })
  child.unref()
  return { ok: true, pid: child.pid, dir, electron }
}

/**
 * Clear the sign-in window's cookies and storage.
 *
 * The session the plugin uses lives in cookies, so signing out must clear them
 * too — otherwise the next time the window opens it is already authenticated and
 * the user cannot switch accounts. The official client does the same on sign-out
 * (it clears cookies for the SSO origin).
 *
 * Runs in a short-lived Electron process, because cookie access needs a session
 * object and the plugin's own host process is not an Electron main process.
 */
export function clearLoginSession({ stateDir, electronPath } = {}) {
  const electron = electronPath || findElectron()
  if (!electron) return { ok: false, error: 'no Electron runtime found' }

  const dir = channelDir(stateDir)
  fs.mkdirSync(dir, { recursive: true })
  const script = path.join(dir, 'clear.cjs')
  fs.writeFileSync(script, `// Generated by dsh-teleagent.
const { app, session } = require('electron')
const fs = require('fs')
const DIR = ${JSON.stringify(dir)}
const done = (v) => { try { fs.writeFileSync(DIR + '/cleared', String(v)) } catch {} ; app.exit(0) }
app.whenReady().then(async () => {
  try {
    const ses = session.fromPartition('persist:teleagent-login')
    await ses.clearStorageData()
    await ses.clearCache()
    done('ok')
  } catch (e) { done('error: ' + (e && e.message || e)) }
})
setTimeout(() => done('timeout'), 8000)
`)

  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE
  try { fs.unlinkSync(path.join(dir, 'cleared')) } catch {}
  const child = spawn(electron, [script], { env, stdio: 'ignore', detached: true })
  child.unref()
  return { ok: true, pid: child.pid }
}

/** Read the outcome of a previous clearLoginSession(). */
export function readClearResult({ stateDir } = {}) {
  try {
    return fs.readFileSync(path.join(channelDir(stateDir), 'cleared'), 'utf8').trim()
  } catch { return null }
}

/** Poll for the window's outcome. */
export function readLoginWindow(stateDir) {
  const dir = channelDir(stateDir)
  const read = (f) => { try { return fs.readFileSync(path.join(dir, f), 'utf8').trim() } catch { return null } }
  const status = read('status')
  const token = read('token')
  return {
    status,
    token,
    error: read('error'),
    currentUrl: read('current-url'),
    dir,
    done: Boolean(token),
    closed: status === 'closed' || status === 'error',
  }
}
